/**
 * Generates the two admin secrets and writes them to a gitignored file.
 *
 * It never prints a secret. Not the hash, not the AUTH_SECRET, not the password
 * you typed. Terminal scrollback gets pasted into chats and screenshots, and
 * this repository is public — a value that reaches either is a value that has
 * been published, and the only remedy is rotating it.
 *
 * Usage:
 *   node scripts/gen-admin-secrets.mjs
 *
 * You will be prompted for a password with no echo. The script writes
 * `.env.admin.local` containing:
 *
 *   ADMIN_PASSWORD_HASH=<argon2id hash of what you typed>
 *   AUTH_SECRET=<32 random bytes, base64>
 *
 * Copy both into Netlify: Site configuration -> Environment variables. Then
 * delete the file, or leave it — it is gitignored either way, and it is also
 * what `.env.local` needs for local admin work.
 *
 * The plaintext password is never written anywhere. If you forget it, run this
 * again and update both values.
 */

import { createInterface } from 'node:readline';
import { randomBytes } from 'node:crypto';
import { writeFileSync, existsSync } from 'node:fs';
import { hash } from '@node-rs/argon2';

const OUTPUT = '.env.admin.local';

/**
 * Read every line of piped stdin up front.
 *
 * Only used when stdin is not a terminal — in that case there is no echo to
 * suppress, and the interactive path's readline never settles because there is
 * no TTY to prompt against.
 */
async function readPipedLines() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString('utf8').split(/\r?\n/);
}

const piped = process.stdin.isTTY ? null : await readPipedLines();
let pipedIndex = 0;

/** Read a line with the terminal echo off, so the password never appears. */
function promptHidden(question) {
  if (piped) return Promise.resolve(piped[pipedIndex++] ?? '');

  return new Promise((resolve) => {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const { output } = rl;

    // Swallow every echoed character while the answer is being typed.
    const onWrite = (_chunk, _encoding, callback) => {
      if (typeof callback === 'function') callback();
      return true;
    };
    const originalWrite = output.write.bind(output);

    originalWrite(question);
    output.write = onWrite;

    rl.question('', (answer) => {
      output.write = originalWrite;
      originalWrite('\n');
      rl.close();
      resolve(answer);
    });
  });
}

if (existsSync(OUTPUT)) {
  console.error(
    `${OUTPUT} already exists. Delete it first if you intend to rotate both secrets.\n` +
      'Rotating means updating the values in Netlify too — the old session cookies stop verifying.',
  );
  process.exit(1);
}

const password = await promptHidden('Admin password (input hidden): ');
const confirm = await promptHidden('Confirm: ');

if (password.length === 0) {
  console.error('Empty password. Nothing written.');
  process.exit(1);
}
if (password !== confirm) {
  console.error('The two entries did not match. Nothing written.');
  process.exit(1);
}
if (password.length < 12) {
  console.error(
    'Use at least 12 characters. This is the only credential on the admin panel, ' +
      'and the panel is reachable from the public internet. Nothing written.',
  );
  process.exit(1);
}

const passwordHash = await hash(password);
const authSecret = randomBytes(32).toString('base64');

writeFileSync(
  OUTPUT,
  [
    '# Generated by scripts/gen-admin-secrets.mjs. Gitignored.',
    '#',
    '# Copy both lines into Netlify: Site configuration -> Environment variables,',
    '# scoped to all deploy contexts. Never commit this file, paste it into a chat,',
    '# or screenshot it — this repository is public.',
    '#',
    '# Rotating: delete this file, run the script again, and update BOTH values in',
    '# Netlify. Existing admin sessions stop verifying immediately.',
    '',
    `ADMIN_PASSWORD_HASH=${passwordHash}`,
    `AUTH_SECRET=${authSecret}`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);

console.log(`\nWrote ${OUTPUT} (nothing printed to this terminal).`);
console.log('\nNext:');
console.log('  1. Open it and copy both variables into Netlify:');
console.log('     Site configuration -> Environment variables -> Add a variable');
console.log('     Names, exactly: ADMIN_PASSWORD_HASH  and  AUTH_SECRET');
console.log(
  '     Scope: all deploy contexts (production, deploy previews, branch deploys)',
);
console.log('  2. For local admin work, append the same two lines to .env.local');
console.log('  3. Redeploy, or the running site will not see them');
